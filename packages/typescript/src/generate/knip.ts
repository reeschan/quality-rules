import { FragmentKind } from '../catalog/fragment-kind.ts';
import { isObject, type Json, type JsonObject, mergeJson, withDefaults } from '../json.ts';
import { fragmentsFor, type Resolution } from '../resolve/resolve.ts';
import { columns, type FormatStyle } from './format.ts';
import type { Generator } from './index.ts';

/** File name of the generated knip preset. */
export const KNIP_FILE = 'knip.mjs';

/**
 * The knip settings of the rules in effect. Rules of the selected packs that are left out
 * turn their issue types `off`, so that knip, which reports every issue type by default,
 * stays quiet about them too.
 */
export function knipConfig(resolution: Resolution): JsonObject {
  const { active, inactive } = fragmentsFor(resolution, FragmentKind.KNIP);
  const merged = active.reduce<Json>(mergeJson, {}) as JsonObject;
  const off: Record<string, Json> = {};
  for (const fragment of inactive) {
    const rules = isObject(fragment.rules) ? fragment.rules : {};
    for (const name of Object.keys(rules)) {
      off[name] = 'off';
    }
  }
  const { rules, ...rest } = merged;
  const allRules = withDefaults(rules ?? {}, off) as JsonObject;
  return Object.keys(allRules).length === 0 ? rest : { ...rest, rules: allRules };
}

/**
 * The source of `quality-rules/knip.mjs`: a module whose default export is the preset. knip
 * has no `extends`, so the project's knip configuration spreads the preset and adds its own
 * `entry` and `ignore` after it.
 */
export function knipSource(config: JsonObject, style: FormatStyle): string {
  const lines = [
    '// Generated by quality-rules from quality-rules.json. Do not edit; run `quality-rules sync`.',
    '// Spread it into the knip configuration of the project and add entry and ignore there.',
    `export default ${renderJs(config, style, 0, columns('export default ', style) + 1)};`,
  ];
  return `${lines.join('\n')}\n`;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/**
 * Writes a JSON value as a JavaScript expression laid out the way Biome formats it: objects
 * one property per line, and arrays of plain values on one line when they fit.
 */
function renderJs(value: Json, style: FormatStyle, depth: number, usedColumns: number): string {
  if (Array.isArray(value)) {
    return renderArray(value, style, depth, usedColumns);
  }
  if (isObject(value)) {
    const entries = Object.entries(value as JsonObject);
    if (entries.length === 0) {
      return '{}';
    }
    const inner = style.indent.repeat(depth + 1);
    const lines = entries.map(([key, item]) => {
      const head = `${inner}${IDENTIFIER.test(key) ? key : quote(key, style)}: `;
      return `${head}${renderJs(item, style, depth + 1, columns(head, style) + 1)}`;
    });
    return `{\n${joinItems(lines, style)}\n${style.indent.repeat(depth)}}`;
  }
  if (typeof value === 'string') {
    return quote(value, style);
  }
  return JSON.stringify(value);
}

function renderArray(
  items: readonly Json[],
  style: FormatStyle,
  depth: number,
  usedColumns: number
): string {
  if (items.length === 0) {
    return '[]';
  }
  if (items.every((item) => !Array.isArray(item) && !isObject(item))) {
    const inline = `[${items.map((item) => renderJs(item, style, depth, 0)).join(', ')}]`;
    if (usedColumns + inline.length <= style.lineWidth) {
      return inline;
    }
  }
  const inner = style.indent.repeat(depth + 1);
  const lines = items.map(
    (item) => `${inner}${renderJs(item, style, depth + 1, columns(inner, style) + 1)}`
  );
  return `[\n${joinItems(lines, style)}\n${style.indent.repeat(depth)}]`;
}

/** Joins the lines of a multi-line object or array, with a comma after the last if wanted. */
function joinItems(lines: readonly string[], style: FormatStyle): string {
  return `${lines.join(',\n')}${style.trailingComma ? ',' : ''}`;
}

/** A string literal in the quote style, switching quotes when that saves escapes as Biome does. */
function quote(text: string, style: FormatStyle): string {
  const other = style.quote === "'" ? '"' : "'";
  const count = (mark: string) => text.split(mark).length - 1;
  const mark = count(style.quote) > count(other) ? other : style.quote;
  const body = JSON.stringify(text)
    .slice(1, -1)
    .replaceAll('\\"', '"')
    .replaceAll(mark, `\\${mark}`);
  return `${mark}${body}${mark}`;
}

/** Generates `quality-rules/knip.mjs`. */
export const knipGenerator: Generator = {
  file: KNIP_FILE,
  guidance: `knip.config.js: import the preset from "./quality-rules/${KNIP_FILE}" and export { ...preset, entry, ignore }`,
  render: (context) => knipSource(knipConfig(context.resolution), context.style),
};
