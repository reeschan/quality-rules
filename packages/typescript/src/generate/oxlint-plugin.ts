import type { Catalog } from '../catalog/types.ts';
import { PLUGIN_NAME } from '../plugin-name.ts';
import { columns, type FormatStyle } from './format.ts';
import type { Generator } from './index.ts';

/** File name of the generated plugin, which `quality-rules/oxlint.json` loads. */
export const OXLINT_PLUGIN_FILE = 'oxlint-plugin.mjs';

/**
 * The source of `quality-rules/oxlint-plugin.mjs`: one plugin named `quality-rules` that holds
 * the custom rules of every installed package that has them. The packages are imported by
 * name, so the file resolves them from the project's `node_modules`.
 */
export function oxlintPluginSource(catalog: Catalog, style: FormatStyle): string {
  const modules = catalog.packages
    .map((item) => item.rulesModule)
    .filter((specifier) => specifier !== undefined);
  const quote = (text: string) => `${style.quote}${text}${style.quote}`;
  const imports = modules.map(
    (specifier, index) => `import * as rules${index} from ${quote(specifier)};`
  );
  const spreads = modules.map((_specifier, index) => `...rules${index}.rules`);
  const lines = [
    '// Generated by quality-rules from quality-rules.json. Do not edit; run `quality-rules sync`.',
    ...imports,
    ...(imports.length > 0 ? [''] : []),
    'export default {',
    `${style.indent}meta: { name: ${quote(PLUGIN_NAME)} },`,
    ...rulesLines(spreads, style),
    '};',
  ];
  return `${lines.join('\n')}\n`;
}

function rulesLines(spreads: readonly string[], style: FormatStyle): string[] {
  const indent = style.indent;
  const lastComma = style.trailingComma ? ',' : '';
  if (spreads.length === 0) {
    return [`${indent}rules: {}${lastComma}`];
  }
  const inline = `${indent}rules: { ${spreads.join(', ')} }${lastComma}`;
  if (columns(inline, style) <= style.lineWidth) {
    return [inline];
  }
  return [
    `${indent}rules: {`,
    ...spreads.map(
      (spread, index) =>
        `${indent}${indent}${spread}${index < spreads.length - 1 ? ',' : lastComma}`
    ),
    `${indent}}${lastComma}`,
  ];
}

/** Generates `quality-rules/oxlint-plugin.mjs`. */
export const oxlintPluginGenerator: Generator = {
  file: OXLINT_PLUGIN_FILE,
  guidance: '',
  render: (context) => oxlintPluginSource(context.catalog, context.style),
};
